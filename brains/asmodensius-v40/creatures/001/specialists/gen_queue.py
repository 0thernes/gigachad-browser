# Generates QUEUE.md from SCORECARD (R21 arm A), LIFE-100, FREAK-100, NOVEL-100, plus status.json (manual overrides).
import re,json,os
B='/workspace/Asmodensius-v40/creatures/001'; ST=json.load(open(f'{B}/specialists/status.json')) if os.path.exists(f'{B}/specialists/status.json') else {}
rows=[]
sc=open(f'{B}/results/official-r21/SCORECARD.md').read()
sec=None
for l in sc.splitlines():
    if l.startswith('## '): sec=l[3:].split()[0]
    m=re.match(r'\| ([^|]+?) \| (PASS|FAIL|PARTIAL|PENDING) \|',l)
    if m and sec in('Butlin','Frameworks','CQM'):
        it,s=m.groups(); st={'PASS':'passed','FAIL':'missing','PARTIAL':'partial','PENDING':'pending'}[s]
        rows.append((0 if st!='passed' else 9,f'{sec}',it.strip(),st+' (R21 A v5.7b)'))
L=open(f'{B}/LIFE-100.md').read().split('\n### ')[1:]
basics=['Body schema','Locomotion','Legs with their own brains','Arms','Reproduction','Mating','Ageing','Death','Decay','Growth','Development']
for blk in L:
    name=blk.split('\n')[0]; ss=re.findall(r'\| (BUILT|PARTIAL|PLANNED|MISSING) \|',blk); nb=ss.count('BUILT')
    st='built' if nb==len(ss) and ss else ('partial' if nb or 'PARTIAL' in ss else 'missing')
    pri=1 if any(k.lower() in name.lower() for k in basics) else 2
    rows.append((pri if st!='built' else 8,'LIFE-100',name,f'{st} ({nb}/{len(ss)} attrs BUILT)'))
for l in open('/workspace/freak-100.md'):
    m=re.match(r'(\d+)\. ([^:]+):',l)
    if m: rows.append((3,'FREAK-100',f'F{m.group(1)} {m.group(2)[:60]}','missing (concept only)'))
for l in open(f'{B}/NOVEL-100.md'):
    m=re.match(r'\| (N\d+) \| ([^|]{0,60})[^|]*\| ([^|]+) \|',l)
    if m: rows.append((4,'NOVEL-100',f'{m.group(1)} {m.group(2).strip()}',m.group(3).strip()))
rows.sort(key=lambda r:r[0])
out=['# Specialist master queue (Creature #1)','',
'Generated by specialists/gen_queue.py; manual progress lives in specialists/status.json. Order: (P0) failing grade-A Butlin/frameworks/CQM, (P1) LIFE-100 missing basics (body, limbs with local brains, mating, ageing, death, decay), (P2) other LIFE-100, (P3) FREAK-100, (P4) NOVEL-100; passed/built items last.',
'','Rules: dev seeds < 1064 only; grade A = d>=0.8 and Welch t>=2.75 vs every control; each specialist has its own ablation/lesion; world stays neutral.',
'Port integration check (Alex): (a) ablating the ported module moves >=2 other subsystems\' measured variables; (b) the module\'s behaviour shifts with internal state (hunger/mood); (c) the specialist test still passes with no regressions.',
'','| # | P | List | Item | Status | Specialist folder | Standalone | Ported | Integ a/b/c | Notes |','|---|---|---|---|---|---|---|---|---|---|']
for i,(p,lst,it,st) in enumerate(rows,1):
    k=f'{lst}:{it.split()[0] if lst!="LIFE-100" else it}'; s=ST.get(k,{})
    out.append(f"| {i} | P{p if p<5 else '-'} | {lst} | {it} | {s.get('status',st)} | {s.get('folder','-')} | {s.get('solo','-')} | {s.get('port','-')} | {s.get('integ','-')} | {s.get('note','')} |")
open(f'{B}/specialists/QUEUE.md','w').write('\n'.join(out)+'\n'); print(len(rows))
